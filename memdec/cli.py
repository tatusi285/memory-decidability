"""Command line interface.

    python -m memdec verify        # do the paper's numbers follow from data/?
    python -m memdec audit         # design audit (the parts the paper omits)
    python -m memdec tables        # regenerate every table as Markdown
    python -m memdec figures       # regenerate every figure as SVG
    python -m memdec build         # all of the above, into analysis_out/
    python -m memdec info          # what is in the manifest
    python -m memdec run --help    # execute a condition (needs a key, or --offline)

Exit codes: 0 success, 1 a claim failed, 2 usage or environment error.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from . import __version__, claims, manifest, paths
from .analysis import audit as audit_mod
from .analysis import figures as figures_mod
from .analysis import tables as tables_mod


def _write(directory: Path, name: str, text: str) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / name
    # newline="\n" keeps generated files identical on Windows and POSIX, which is what
    # the CI drift check (`git diff --exit-code docs/`) relies on.
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def cmd_verify(args: argparse.Namespace) -> int:
    results = claims.evaluate()
    report = "\n".join([
        "# Claim verification",
        "",
        "*Generated by `python -m memdec verify`. Do not edit by hand.*",
        "",
        "Every number below is recomputed from `data/` and compared with the value the "
        "manuscript reports. A pass means the manuscript is consistent with the shipped "
        "results; it is not a replication, which would need new model calls.",
        "",
        claims.render_results(results, "Published values"),
        "",
        claims.render_extra(),
        "",
        claims.render_disputes(),
        "",
    ])
    path = _write(paths.docs_dir(), "CLAIMS.md", report)
    print(report)
    passed = sum(1 for r in results if r.ok)
    print(f"\n{passed}/{len(results)} published values reproduced.")
    print(f"report: {path}")
    return 0 if passed == len(results) else 1


def cmd_audit(args: argparse.Namespace) -> int:
    text = audit_mod.build_audit_report()
    path = _write(paths.docs_dir(), "AUDIT.md", text)
    items = audit_mod.findings()
    print(f"design audit -> {path}\n")
    for finding in items:
        print(f"  [{finding.severity:<7}] {finding.ident}: {finding.title}")
    counts = {}
    for finding in items:
        counts[finding.severity] = counts.get(finding.severity, 0) + 1
    print("\n" + ", ".join(f"{k}: {v}" for k, v in counts.items()))
    return 0


def cmd_tables(args: argparse.Namespace) -> int:
    out = paths.docs_dir() / "tables"
    produced = {}
    for name, text in tables_mod.all_tables().items():
        produced[name] = _write(out, f"{name}.md", text + "\n")
    inventory = _write(out, "run_inventory.md", tables_mod.inventory() + "\n")
    print(f"{len(produced) + 1} tables written to {out}")
    for path in produced.values():
        print(f"  {path.name}")
    print(f"  {inventory.name}")
    return 0


def cmd_figures(args: argparse.Namespace) -> int:
    out = paths.docs_dir() / "figures"
    written = figures_mod.write_figures(out)
    print(f"{len(written)} figures written to {out}")
    for path in written:
        print(f"  {path.name}")
    return 0


def cmd_build(args: argparse.Namespace) -> int:
    code = cmd_verify(args)
    cmd_audit(args)
    cmd_tables(args)
    cmd_figures(args)
    return code


def cmd_info(args: argparse.Namespace) -> int:
    runs = manifest.load_runs()
    total = sum(spec.probes for spec in runs.values())
    print(f"repo: {paths.repo_root()}")
    print(f"runs: {len(runs)}   probes: {total:,}")
    models = sorted({spec.model for spec in runs.values()})
    corpora = sorted({spec.corpus for spec in runs.values()})
    print(f"models: {', '.join(models)}")
    print(f"corpora: {', '.join(corpora)}")
    print()
    print(tables_mod.inventory())
    return 0


def cmd_run(args: argparse.Namespace) -> int:
    from .client import find_api_key
    from .runner import RunConfig, run, write_meta, write_results

    cfg = RunConfig(
        model=args.model,
        base_url=args.base_url,
        chains=args.chains,
        delays=tuple(float(x) for x in args.delays.split(",") if x.strip()),
        seeds=args.seeds,
        policies=tuple(p.strip() for p in args.policies.split(",") if p.strip()),
        review_ratio=args.review_ratio,
        review_budget_chars=args.review_budget,
        ctx_budget=args.ctx_budget,
        time_format=args.time_format,
        text_style=args.text_style,
        ctx_order=args.ctx_order,
        filler_k=args.filler_k,
        filler_mode=args.filler_mode,
        corpus=args.corpus,
        corpus_file=(paths.data_dir() / "corpus" / "real_chains.json"
                     if args.corpus == "real" else None),
        importance_mode=args.importance_mode,
        importance_signal=args.importance_signal,
        late_duplicates=args.late_duplicates,
        max_tokens=args.max_tokens,
        concurrency=args.concurrency,
        offline=args.offline,
        out=Path(args.out),
    )

    key, key_env = "", ""
    if not args.offline:
        key, key_env = find_api_key(args.api_key_env)
        if not key:
            print(f"no API key found. Set one of: {args.api_key_env}\n"
                  "Use --offline to exercise the pipeline with the rule simulator.",
                  file=sys.stderr)
            return 2

    result = run(cfg, api_key=key, key_env=key_env)
    out = Path(args.out)
    write_results(result.rows, out)
    write_meta(result.meta, out)

    print(f"condition: {cfg.model} | {cfg.time_format}/{cfg.ctx_order}/{cfg.text_style} "
          f"| {cfg.corpus}")
    print(f"{'policy':<12}{'reviewed':>9}{'archived':>9}{'coverage':>10}{'hit rate':>10}")
    for outcome in _last_seed_outcomes(result.outcomes, len(cfg.delays), len(cfg.policies)):
        print(f"{outcome.policy:<12}{outcome.reviewed:>9}{outcome.archived:>9}"
              f"{outcome.coverage * 100:>9.1f}%{outcome.conflict_hit_rate * 100:>9.1f}%")
    if result.meta["simulated"]:
        print("\nNOTE: --offline used the rule simulator. These numbers are a plumbing "
              "test, not measurements. Do not report them.")
    print(f"wrote {out / 'results.csv'} and {out / 'run_meta.json'}")
    return 0


def _last_seed_outcomes(outcomes, n_delays: int, n_policies: int):
    """Show the accounting for one (delay, seed) block, not the whole grid."""
    block = outcomes[-n_policies:]
    return block


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="memdec",
        description="Reproducibility toolkit for the Decidability Before Maintenance study.",
    )
    parser.add_argument("--version", action="version", version=f"memdec {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    for name, func, help_text in (
        ("verify", cmd_verify, "recompute the paper's numbers from data/"),
        ("audit", cmd_audit, "run the design audit"),
        ("tables", cmd_tables, "regenerate every table as Markdown"),
        ("figures", cmd_figures, "regenerate every figure as SVG"),
        ("build", cmd_build, "verify + audit + tables + figures"),
        ("info", cmd_info, "describe the shipped manifest"),
    ):
        p = sub.add_parser(name, help=help_text)
        p.set_defaults(func=func)

    p = sub.add_parser("run", help="execute a condition grid")
    p.set_defaults(func=cmd_run)
    p.add_argument("--model", default="deepseek-chat")
    p.add_argument("--base-url", default="https://api.deepseek.com/v1")
    p.add_argument("--chains", type=int, default=40)
    p.add_argument("--delays", default="1,7,30,90")
    p.add_argument("--seeds", type=int, default=3)
    p.add_argument("--policies", default="none,recent,importance,decay")
    p.add_argument("--review-ratio", type=float, default=0.4)
    p.add_argument("--review-budget", type=int, default=0)
    p.add_argument("--ctx-budget", type=int, default=1200)
    p.add_argument("--time-format", choices=["date", "day", "none"], default="none")
    p.add_argument("--text-style", default="template",
                   choices=["template", "uniform", "natural", "vary_source",
                            "vary_structure", "vary_number"])
    p.add_argument("--ctx-order", choices=["newest_first", "oldest_first", "random"],
                   default="newest_first")
    p.add_argument("--filler-k", type=int, default=0)
    p.add_argument("--filler-mode", choices=["tail", "gap", "prefix"], default="tail")
    p.add_argument("--corpus", choices=["synthetic", "real"], default="synthetic")
    p.add_argument("--importance-mode", choices=["random", "signal"], default="random",
                   help="random reproduces the shipped design; signal correlates importance "
                        "with supersession")
    p.add_argument("--importance-signal", type=float, default=0.0,
                   help="strength of the importance/conflict correlation in [0, 1]")
    p.add_argument("--late-duplicates", type=float, default=0.0,
                   help="fraction of chains whose stale record is written after the "
                        "update, breaking the recency/conflict correlation")
    p.add_argument("--max-tokens", type=int, default=24)
    p.add_argument("--concurrency", type=int, default=6)
    p.add_argument("--api-key-env", default="MEMDEC_API_KEY,DEEPSEEK_API_KEY,OPENAI_API_KEY")
    p.add_argument("--offline", action="store_true",
                   help="use the deterministic rule simulator instead of a model")
    p.add_argument("--out", default="out")
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except FileNotFoundError as exc:
        print(f"missing artifact: {exc}", file=sys.stderr)
        return 2
    except RuntimeError as exc:
        print(f"{exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
